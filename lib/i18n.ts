export function getStoredLanguage(): SupportedLanguage {
  if (typeof window === 'undefined') return 'en';
  try {
    const stored = localStorage.getItem('ledgerclean_language') as SupportedLanguage;
    if (stored && ['en', 'es', 'fr', 'de', 'pt', 'ja'].includes(stored)) {
      return stored;
    }
  } catch (e) {
    // Fallback
  }
  return 'en';
}

export function setStoredLanguage(lang: SupportedLanguage) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem('ledgerclean_language', lang);
  } catch (e) {
    // Fallback
  }
}

export function translate(key: string, lang: SupportedLanguage = 'en'): string {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dictionary[key] || TRANSLATIONS.en[key] || key;
}
